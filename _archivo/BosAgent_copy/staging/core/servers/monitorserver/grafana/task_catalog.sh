#!/usr/bin/env bash
# task_catalog.sh — Grafana 11.5 observability task handlers
# Ficha 15 · Order 210 · SBOS-019 §9
# Degraded mode: health tolerates missing Prometheus datasource
# R16: no hardcoded paths. All paths from env vars with defaults.

set -euo pipefail

export SBOS_FICHA_DIR="${SBOS_FICHA_DIR:-/etc/bos/blibs/servers/monitorserver/grafana}"
export SBOS_NAMESPACE="${SBOS_NAMESPACE:-sbos-monitor}"

# ── pre_install ────────────────────────────────────────────────
ficha_pre_install() {
    echo "${__SBOS__STEP_START__} pre_install"
    echo "${__SBOS__STEP_OK__} pre_install"
}

# ── install ────────────────────────────────────────────────────
ficha_install() {
    echo "${__SBOS__STEP_START__} install"
    sbos_k8s_core "${SBOS_FICHA_DIR}/grafana.k8s.yml" "${SBOS_NAMESPACE}"
    kubectl wait --for=condition=Available deployment/grafana -n "${SBOS_NAMESPACE}" --timeout=600s
    echo "${__SBOS__STEP_OK__} install"
}

# ── post_install ───────────────────────────────────────────────
ficha_post_install() {
    echo "${__SBOS__STEP_START__} post_install"
    curl -sf http://localhost:3000/api/health
    echo "${__SBOS__STEP_OK__} post_install"
}

# ── update ─────────────────────────────────────────────────────
ficha_update() {
    echo "${__SBOS__STEP_START__} update"
    kubectl rollout restart deployment grafana -n "${SBOS_NAMESPACE}"
    kubectl wait --for=condition=Available deployment/grafana -n "${SBOS_NAMESPACE}" --timeout=300s
    echo "${__SBOS__STEP_OK__} update"
}

# ── repair ─────────────────────────────────────────────────────
ficha_repair() {
    echo "${__SBOS__STEP_START__} repair"
    kubectl rollout restart deployment grafana -n "${SBOS_NAMESPACE}"
    echo "${__SBOS__STEP_OK__} repair"
}

# ── uninstall ──────────────────────────────────────────────────
ficha_uninstall() {
    echo "${__SBOS__STEP_START__} uninstall"
    kubectl delete deployment grafana -n "${SBOS_NAMESPACE}" --ignore-not-found
    kubectl delete pvc grafana-data -n "${SBOS_NAMESPACE}" --ignore-not-found
    echo "${__SBOS__STEP_OK__} uninstall"
}

# ── health ─────────────────────────────────────────────────────
ficha_health() {
    echo "${__SBOS__STEP_START__} health"
    curl -sf http://localhost:3000/api/health
    echo "${__SBOS__STEP_OK__} health"
}
